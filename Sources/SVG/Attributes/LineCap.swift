extension SVG {

	/// A type representing a line cap.
	public enum LineCap: String, Sendable {

		/// Specifies a `butt` cap.
		case butt

		/// Specifies a `round` cap.
		case round

		/// Specifies a `square` cap.
		case square
	}
}
